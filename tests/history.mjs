import assert from 'node:assert/strict';
import {taskSource,relativeTime,historyEntries,filterHistory,mediaUrl,retainedHistory} from '../public/history-model.js';
const now=Date.parse('2026-10-12T08:00:00Z');
assert.equal(relativeTime(new Date(now-30000).toISOString(),now),'Just now');
assert.equal(relativeTime(new Date(now-120000).toISOString(),now),'2m ago');
assert.equal(relativeTime(new Date(now-7200000).toISOString(),now),'2h ago');
assert.equal(relativeTime(new Date(now-172800000).toISOString(),now),'2d ago');
assert.equal(relativeTime('invalid',now),'Time unavailable');
assert.equal(relativeTime(new Date(now+1000).toISOString(),now),'Just now');
assert.equal(taskSource({meta:{source:'api_request',operation:'text-to-image'}}),'api_request','explicit sources override legacy inference');
assert.equal(taskSource({meta:{operation:'text-to-image'}}),'interface','legacy interface records retain a usable source');
assert.equal(taskSource({}),'api_request');
const oldTime=new Date(now-25*60*60*1000).toISOString();
assert.deepEqual(retainedHistory([{id:'old-api',createdAt:oldTime,meta:{source:'api_request'}},{id:'old-interface',createdAt:oldTime,meta:{source:'interface'}},{id:'new-api',createdAt:new Date(now).toISOString(),meta:{source:'api_request'}}],now).map(task=>task.id),['old-interface','new-api'],'API history has a one-day display window; retained interface records remain available');
const tasks=[{id:'a',modelId:'flux',createdAt:'2026-10-12T07:00:00Z',status:'succeeded',meta:{prompt:'Orange cat',source:'interface'},outputs:[{kind:'image'},{kind:'image'}]},{id:'b',modelId:'seedream',createdAt:'2026-10-12T07:30:00Z',status:'failed',meta:{prompt:'A beach',source:'api_request'}},{id:'c',modelId:'dreamvideo',createdAt:'2026-10-12T06:30:00Z',status:'processing',meta:{source:'api_request'}}];
const entries=historyEntries(tasks);
assert.deepEqual(entries.map(entry=>entry.task.id),['b','a','a','c'],'history orders submissions newest first and keeps every output');
assert.equal(filterHistory(entries,{sources:['interface']}).length,2);
assert.equal(filterHistory(entries,{sources:[]}).length,0);
assert.equal(filterHistory(entries,{status:'failed'})[0].task.id,'b');
assert.equal(filterHistory(entries,{status:'generating'})[0].task.id,'c');
assert.equal(filterHistory(entries,{query:'ORANGE'}).length,2);
assert.equal(filterHistory(entries,{query:'seedream'}).length,1);
assert.equal(mediaUrl({url:'javascript:alert(1)'}),'');
assert.equal(mediaUrl({url:'//other.test/file.png'}),'');
assert.equal(mediaUrl({localUrl:'/local/outputs/task-0.png',url:'https://provider.test/output.png'}),'/local/outputs/task-0.png');
console.log('History sources, legacy compatibility, sorting, multiple outputs, relative times, filtering, and media URL validation passed.');
